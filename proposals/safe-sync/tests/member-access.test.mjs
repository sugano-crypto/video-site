test('media endpoint rechecks user/RLS and never signs for a denied article',async()=>{
 let signs=0,reads=0;
 const io={base:'https://project.supabase.co',ready:async()=>true,user:async t=>t==='valid'?{id:'user'}:null,article:async()=>{reads++;return null;},sign:async()=>{signs++;return 'signed';}};
 const handler=mediaHandler(io);
 const request=token=>new Request('https://local/',{method:'POST',headers:{authorization:'Bearer '+token},body:'{"article_id":"1"}'});
 assert.equal((await handler(request('invalid'))).status,401);assert.equal(reads,0);
 assert.equal((await handler(request('valid'))).status,404);assert.equal(signs,0);
 io.article=async()=>({notion_audio_url:'https://project.supabase.co/storage/v1/object/public/article-media/TOPIC/audio.mp3'});
 const response=await handler(request('valid'));assert.equal(response.status,200);assert.equal((await response.json()).expires_in,300);assert.equal(signs,1);
 io.ready=async()=>false;assert.equal((await handler(request('valid'))).status,503);assert.equal(signs,1);
});

